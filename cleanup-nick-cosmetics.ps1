<#
  cleanup-nick-cosmetics.ps1
  ---------------------------------------------------------------
  Cleans up nick-cosmetics-python-platform by MOVING junk files
  into a dated "_cleanup_review" folder at the project root.
  NOTHING IS PERMANENTLY DELETED except __pycache__ folders,
  which are 100% auto-regenerated by Python and always safe.

  USAGE:
    1. Edit $ProjectRoot below if needed.
    2. Open PowerShell in the project folder.
    3. Dry run first (shows what WOULD move, changes nothing):
         .\cleanup-nick-cosmetics.ps1
    4. When happy, actually move the files:
         .\cleanup-nick-cosmetics.ps1 -Apply
    5. Review the _cleanup_review folder yourself, then delete it
       (or restore anything you want back) once you're confident.

  NOTE ON venv/.venv:
    These are NOT moved - they're 130MB+ of installed packages,
    not something to shuffle around. Just make sure "venv/" and
    ".venv/" are in your .gitignore and never zip them again.
    If you ever want to reclaim the disk space, delete the folder
    and recreate it with: python -m venv venv ; pip install -r requirements.txt
#>

param(
    [switch]$Apply,
    [string]$ProjectRoot = "C:\Dev\nick-cosmetics-python-platform"
)

$ErrorActionPreference = "Stop"
$stamp = Get-Date -Format "yyyyMMdd_HHmmss"
$reviewFolder = Join-Path $ProjectRoot "_cleanup_review_$stamp"

if (-not (Test-Path $ProjectRoot)) {
    Write-Host "Project root not found: $ProjectRoot" -ForegroundColor Red
    exit 1
}

Write-Host "Project root: $ProjectRoot"
Write-Host "Mode: $(if ($Apply) { 'APPLY (files will be moved)' } else { 'DRY RUN (nothing will change)' })" -ForegroundColor Yellow
Write-Host ""

# ---------------------------------------------------------------
# 1. __pycache__ folders - always safe to hard-delete (regenerated)
# ---------------------------------------------------------------
$pycacheDirs = Get-ChildItem -Path $ProjectRoot -Directory -Recurse -Filter "__pycache__" -ErrorAction SilentlyContinue |
    Where-Object { $_.FullName -notmatch '\\venv\\|\\.venv\\|\\_cleanup_review_' }

Write-Host "=== __pycache__ folders (will be DELETED, not moved): $($pycacheDirs.Count) found ===" -ForegroundColor Cyan
foreach ($d in $pycacheDirs) {
    Write-Host "  DELETE: $($d.FullName)"
    if ($Apply) { Remove-Item -Recurse -Force -LiteralPath $d.FullName }
}
Write-Host ""

# ---------------------------------------------------------------
# 2. Named archive / backup folders - moved wholesale
# ---------------------------------------------------------------
$archiveFolderNames = @(
    "_archive", "_pre_copy_backup"
)
$archiveFolderPatterns = @(
    "_nav_backup_*"
)

$foldersToMove = New-Object System.Collections.Generic.List[string]

foreach ($name in $archiveFolderNames) {
    Get-ChildItem -Path $ProjectRoot -Directory -Recurse -Filter $name -ErrorAction SilentlyContinue |
        Where-Object { $_.FullName -notmatch '\\venv\\|\\.venv\\|\\_cleanup_review_' } |
        ForEach-Object { $foldersToMove.Add($_.FullName) }
}
foreach ($pattern in $archiveFolderPatterns) {
    Get-ChildItem -Path $ProjectRoot -Directory -Recurse -Filter $pattern -ErrorAction SilentlyContinue |
        Where-Object { $_.FullName -notmatch '\\venv\\|\\.venv\\|\\_cleanup_review_' } |
        ForEach-Object { $foldersToMove.Add($_.FullName) }
}

Write-Host "=== Archive/backup folders (will be MOVED): $($foldersToMove.Count) found ===" -ForegroundColor Cyan
foreach ($f in $foldersToMove) {
    $rel = $f.Substring($ProjectRoot.Length).TrimStart('\')
    $dest = Join-Path $reviewFolder $rel
    Write-Host "  MOVE: $f"
    if ($Apply) {
        New-Item -ItemType Directory -Force -Path (Split-Path $dest) | Out-Null
        Move-Item -LiteralPath $f -Destination $dest -Force
    }
}
Write-Host ""

# ---------------------------------------------------------------
# 3. Junk FILES by pattern - moved individually
# ---------------------------------------------------------------
$filePatterns = @(
    "*.bak", "*.bak[0-9]*", "*.bak_fix*", "*.mojibake.bak",
    "diagnose*.txt", "diagnose*.ps1", "diagnose*.csv",
    "fix*.py", "fix*.ps1",
    "apply_*.ps1", "apply_*.py", "setup-*.ps1", "create_coupon_module*.ps1",
    "*.jsx",
    "cleanup_*.ps1", "patch_*.ps1", "check-encoding-damage.ps1",
    "_archive_manifest_*.csv", "backup_comparison_v2.csv", "compare_backups.py",
    "root_tree.txt", "pos_window_dump.txt", "_discovery_*.txt", "_dump_for_claude*.txt",
    "for-claude*.zip", "diag_encoding.py", "fix_encoding.py",
    "PASTE_REAL_PATH_HERE", "*.db"
)

$filesToMove = New-Object System.Collections.Generic.List[string]
foreach ($pattern in $filePatterns) {
    Get-ChildItem -Path $ProjectRoot -File -Recurse -Filter $pattern -ErrorAction SilentlyContinue |
        Where-Object { $_.FullName -notmatch '\\venv\\|\\.venv\\|\\_cleanup_review_|\\node_modules\\' } |
        ForEach-Object { $filesToMove.Add($_.FullName) }
}
# Any filename containing spaces + a PowerShell-looking fragment (accidental paste-into-filename mistakes)
Get-ChildItem -Path $ProjectRoot -File -Recurse -ErrorAction SilentlyContinue |
    Where-Object { $_.Name -match ' Select-String| -Pattern | -Context' } |
    ForEach-Object { $filesToMove.Add($_.FullName) }

$filesToMove = $filesToMove | Select-Object -Unique

Write-Host "=== Junk files (will be MOVED): $($filesToMove.Count) found ===" -ForegroundColor Cyan
foreach ($f in $filesToMove) {
    $rel = $f.Substring($ProjectRoot.Length).TrimStart('\')
    $dest = Join-Path $reviewFolder $rel
    Write-Host "  MOVE: $f"
    if ($Apply) {
        New-Item -ItemType Directory -Force -Path (Split-Path $dest) | Out-Null
        Move-Item -LiteralPath $f -Destination $dest -Force
    }
}
Write-Host ""

# ---------------------------------------------------------------
# Summary
# ---------------------------------------------------------------
Write-Host "---------------------------------------------------------------"
if ($Apply) {
    Write-Host "Done. Review folder: $reviewFolder" -ForegroundColor Green
    Write-Host "Once you're confident nothing important got swept up, delete that folder."
} else {
    Write-Host "This was a DRY RUN - nothing was changed." -ForegroundColor Yellow
    Write-Host "Re-run with -Apply to actually move/delete the items listed above:"
    Write-Host "  .\cleanup-nick-cosmetics.ps1 -Apply"
}
Write-Host "venv/.venv were left alone on purpose - see the note at the top of this script."
